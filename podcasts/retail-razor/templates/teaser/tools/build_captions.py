"""Build compositions/captions.html for a TRRS 16:9 teaser: continuous spoken-word captions.

Style (S6E15 teaser v7, CD-approved): Montserrat 800 54px cream #fbeee6, sentence case, centred in a 1600px column
at top 930; lines <= 5 words / <= 1.8 s, break on punctuation (or a comma once the line has 2+ words) or a >0.7 s gap;
a line NEVER spans a segment cut; the spoken word lights peach #f2b48c then settles to cream.
The teaser ends on a line cut off mid-sentence: its last word gets an ellipsis and holds to --cutoff-end.

Inputs:
  --words  master-relative words, either [{"w","s","e"}] or faster-whisper style [{"text","start","end"}].
           Must be VERBATIM to the audio: correct ASR spellings first (--fix) and check every line by ear.
  --cuts   comma list of master cut times (segment boundaries from EDL.md), e.g. "4.9,9.5,12.5"
  --fix    optional JSON file: [["asr word seq lowercase", "Verbatim Replacement Seq"], ...] applied in order,
           each sequence must be found once (e.g. [["ice media", "Iced Media"], ["redditors", "Redditors"]]).
  --cutoff-end  time the cut-off line's caption must end (= the hard voice cut). Omit if the teaser has no cut-off.
Usage:
  python build_captions.py --words voice_words.json --out ../compositions/captions.html --cuts "4.9,9.5,..." \
      --fix fixes.json --cutoff-end 55.567
"""
import argparse, html, json, re

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--words", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--cuts", default="")
ap.add_argument("--fix", default=None)
ap.add_argument("--cutoff-end", type=float, default=None)
a = ap.parse_args()

raw = json.load(open(a.words, encoding="utf8"))
words = [{"t": (w.get("w") or w.get("text")).strip(), "s": w.get("s", w.get("start")), "e": w.get("e", w.get("end"))} for w in raw]

if a.fix:
    for seq, repl in json.load(open(a.fix, encoding="utf8")):
        seq, repl = seq.split(), repl.split()
        n = len(seq)
        for i in range(len(words) - n + 1):
            if [x["t"].lower().strip(".,?!") for x in words[i:i + n]] == seq:
                for k, r in enumerate(repl):
                    words[i + k]["t"] = r
                break
        else:
            raise SystemExit(f"fix not found: {seq}")

if a.cutoff_end is not None:
    words[-1]["t"] = words[-1]["t"].rstrip(".,") + "…"

CUTS = [float(c) for c in a.cuts.split(",") if c.strip()]
seg = lambda t: sum(1 for c in CUTS if t >= c)
wseg = lambda w: seg((w["s"] + w["e"]) / 2)

lines, cur = [], []
for w in words:
    if cur and (len(cur) >= 5 or w["e"] - cur[0]["s"] > 1.8 or wseg(w) != wseg(cur[0]) or w["s"] - cur[-1]["e"] > 0.7):
        lines.append(cur); cur = []
    cur.append(w)
    if re.search(r"[.?!…]$", w["t"]) or (w["t"].endswith(",") and len(cur) >= 2):
        lines.append(cur); cur = []
if cur:
    lines.append(cur)

out = []
for i, ln in enumerate(lines):
    sg = wseg(ln[0])
    start = round(max(0.0, ln[0]["s"] - 0.05), 3)
    if sg > 0:
        start = max(start, CUTS[sg - 1])
    nxt = lines[i + 1][0]["s"] - 0.05 if i + 1 < len(lines) else ln[-1]["e"] + 0.4
    end = min(ln[-1]["e"] + 0.35, nxt)
    if sg < len(CUTS) and end > CUTS[sg]:
        end = CUTS[sg]
    if a.cutoff_end is not None and ln[-1]["t"].endswith("…"):
        end = a.cutoff_end
    if end - start <= 0.05:
        raise SystemExit(f"line at {start:.2f} has no room (ends {end:.2f}): words run past a cut or --cutoff-end")
    out.append({"id": f"c{i}", "start": start, "dur": round(end - start, 3), "words": ln})

ROWS, SPANS = [], []
for L in out:
    spans = " ".join(f'<span id="{L["id"]}w{k}" class="cw">{html.escape(w["t"])}</span>' for k, w in enumerate(L["words"]))
    ROWS.append(f'    <div id="{L["id"]}" class="cl clip" data-start="{L["start"]}" data-duration="{L["dur"]}" data-track-index="{len(ROWS) % 3}">{spans}</div>')
    for k, w in enumerate(L["words"]):
        SPANS.append([f'#{L["id"]}w{k}', round(w["s"], 3), round(w["e"], 3)])

doc = f'''<template>
  <!-- GENERATED by tools/build_captions.py: do not hand-edit. -->
  <style>
    @font-face {{ font-family: "Montserrat"; src: url("assets/fonts/Montserrat.ttf") format("truetype"); font-weight: 100 900; font-display: block; }}
    #root {{ position: absolute; inset: 0; pointer-events: none; font-family: "Montserrat", sans-serif; }}
    .cl {{ position: absolute; left: 160px; width: 1600px; top: 930px; text-align: center; white-space: nowrap;
      font-size: 54px; font-weight: 800; letter-spacing: -0.01em; line-height: 1; color: #fbeee6;
      text-shadow: 0 2px 0 rgba(0,0,0,0.55), 0 0 18px rgba(0,0,0,0.75), 0 0 4px rgba(0,0,0,0.9); }}
    .cw {{ display: inline-block; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080" data-layout-allow-overflow data-layout-allow-overlap>
{chr(10).join(ROWS)}
  </div>
  <script>
    (function () {{
      // Spoken-word captions: each word lights peach while it is spoken, then settles to cream
      const tl = gsap.timeline({{ paused: true }});
      const W = {json.dumps(SPANS)};
      W.forEach(([s, a, b]) => {{
        tl.set(s, {{ color: "#f2b48c" }}, a);
        tl.set(s, {{ color: "#fbeee6" }}, Math.max(a + 0.08, b));
      }});
      document.querySelectorAll(".cl").forEach((el) => {{
        const t = parseFloat(el.dataset.start);
        tl.fromTo(el, {{ opacity: 0, y: 10 }}, {{ opacity: 1, y: 0, duration: 0.12, ease: "power2.out" }}, t);
      }});
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
'''
open(a.out, "w", encoding="utf8").write(doc)
for L in out:
    print(f'{L["start"]:6.2f} +{L["dur"]:.2f}  ' + " ".join(w["t"] for w in L["words"]))
