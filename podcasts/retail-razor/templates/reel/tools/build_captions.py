"""Build compositions/captions.html for a TRRS 9:16 reel: word-synced captions from words.json.

Approved S6E15 style (do not change without the CD): uppercase Montserrat 900 76px, cream #fbeee6,
centred in a 960px column at top 1290; <= 3 words, <= 16 characters and <= 1.2 s per line, break on
punctuation or a >0.5 s gap; the spoken word lights peach #f2b48c then settles to cream; KEY words stay red.

words.json: [{"w": "Word,", "s": 0.12, "e": 0.40, "spk": "guest"}, ...] cut-relative and VERBATIM to the
final voice.wav (verify by re-transcribing the final audio, never from show notes alone).

Usage (from anywhere):
  python build_captions.py --words <words.json> --out <project>/compositions/captions.html \
      --end <outro start s> --key "geo,seo,legacy"
  --end defaults to last word end + 0.4. --key is a comma list, matched case-insensitively with
  trailing punctuation stripped. Prints the line list for a quick read-through.
"""
import argparse, html, json, re

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--words", required=True, help="cut-relative words.json")
ap.add_argument("--out", required=True, help="path of compositions/captions.html to write")
ap.add_argument("--end", type=float, default=None, help="caption track end = outro start (s)")
ap.add_argument("--key", default="", help="comma-separated key words shown in red")
ap.add_argument("--max-words", type=int, default=3)
ap.add_argument("--max-chars", type=int, default=16, help="76px caps fit ~16 characters in 960px")
ap.add_argument("--max-line-s", type=float, default=1.2)
a = ap.parse_args()

W = json.load(open(a.words, encoding="utf8"))
END = a.end if a.end is not None else W[-1]["e"] + 0.4
KEY = {k.strip().lower() for k in a.key.split(",") if k.strip()}
PUNCT = ".,?!—…"

words = [{"t": w["w"], "s": w["s"], "e": w["e"]} for w in W]
lines, cur = [], []
for w in words:
    chars = len(" ".join(x["t"] for x in cur + [w]))
    if cur and (len(cur) >= a.max_words or chars > a.max_chars or w["e"] - cur[0]["s"] > a.max_line_s or w["s"] - cur[-1]["e"] > 0.5):
        lines.append(cur); cur = []
    cur.append(w)
    if re.search(r"[.?!,—…]$", w["t"]):
        lines.append(cur); cur = []
if cur:
    lines.append(cur)

out = []
for i, ln in enumerate(lines):
    start = round(max(0.0, ln[0]["s"] - 0.04), 3)
    nxt = lines[i + 1][0]["s"] - 0.04 if i + 1 < len(lines) else END
    end = min(ln[-1]["e"] + 0.3, nxt, END)
    out.append({"id": f"c{i}", "start": start, "dur": round(end - start, 3), "words": ln})


def is_key(w):
    return w["t"].lower().strip(PUNCT) in KEY


ROWS, SPANS = [], []
for L in out:
    spans = " ".join(
        f'<span id="{L["id"]}w{k}" class="{"cw key" if is_key(w) else "cw"}">{html.escape(w["t"])}</span>'
        for k, w in enumerate(L["words"]))
    ROWS.append(f'    <div id="{L["id"]}" class="cl clip" data-start="{L["start"]}" data-duration="{L["dur"]}" data-track-index="{len(ROWS) % 3}">{spans}</div>')
    for k, w in enumerate(L["words"]):
        if not is_key(w):
            SPANS.append([f'#{L["id"]}w{k}', round(w["s"], 3), round(w["e"], 3)])

doc = f'''<template>
  <!-- GENERATED by tools/build_captions.py: do not hand-edit; fix words.json / --key and re-run. -->
  <style>
    @font-face {{ font-family: "Montserrat"; src: url("assets/fonts/Montserrat.ttf") format("truetype"); font-weight: 100 900; font-display: block; }}
    #root {{ position: absolute; inset: 0; pointer-events: none; font-family: "Montserrat", sans-serif; }}
    .cl {{ position: absolute; left: 60px; width: 960px; top: 1290px; text-align: center; white-space: nowrap;
      font-size: 76px; font-weight: 900; letter-spacing: -0.02em; line-height: 1; color: #fbeee6; text-transform: uppercase;
      text-shadow: 0 3px 0 rgba(0,0,0,0.6), 0 0 22px rgba(0,0,0,0.8), 0 0 5px rgba(0,0,0,0.9); }}
    .cw {{ display: inline-block; }}
    .key {{ color: #ff3b44; text-shadow: 0 3px 0 rgba(0,0,0,0.7), 0 0 8px rgba(0,0,0,0.95), 0 0 22px rgba(0,0,0,0.85); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920" data-layout-allow-overflow data-layout-allow-overlap>
{chr(10).join(ROWS)}
  </div>
  <script>
    (function () {{
      // Spoken-word captions: the word being said lights peach, then settles to cream; key words stay red
      const tl = gsap.timeline({{ paused: true }});
      const W = {json.dumps(SPANS)};
      W.forEach(([s, a, b]) => {{
        tl.set(s, {{ color: "#f2b48c" }}, a);
        tl.set(s, {{ color: "#fbeee6" }}, Math.max(a + 0.08, b));
      }});
      document.querySelectorAll(".cl").forEach((el) => {{
        const t = parseFloat(el.dataset.start);
        tl.fromTo(el, {{ opacity: 0, scale: 0.92 }}, {{ opacity: 1, scale: 1, duration: 0.14, ease: "back.out(2)" }}, t);
      }});
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
'''
open(a.out, "w", encoding="utf8").write(doc)
for L in out:
    print(f'{L["start"]:6.2f} +{L["dur"]:.2f}  ' + " ".join(w["t"] for w in L["words"]))
